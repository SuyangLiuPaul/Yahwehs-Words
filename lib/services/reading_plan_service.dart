/// Reading plans, 2026-10-15.
///
/// The owner asked for them back. The feature that was deleted in
/// v1.2.69 left two lessons, and both shape this file:
///
///  * Its progress lived under dotted keys (`plan.activeId`,
///    `plan.completed.<id>`). Firebase RTDB forbids `.` in keys, so once
///    those keys were in the sync schema every legacy reader's upload was
///    rejected (the v1.3.45 hotfix). Progress is now ONE key with no dot,
///    [kReadingPlanKey], holding a JSON blob; the blob's contents are a
///    value, not keys, so RTDB never sees them as paths.
///  * Its data was not what it said (a "chronological" plan identical to
///    the canonical one). The schedules are now generated by
///    `tools/build_reading_plans.py` from this repo's own KJV and a test
///    re-checks them: every chapter once, in order.
///
/// The legacy `plan.*` prefs are left exactly where they are — nothing
/// here reads, migrates or deletes them (see profile_service.dart).
const String kReadingPlanKey = 'readingPlan';

/// One run inside one book: whole chapters (`Genesis 1-3`) or, where
/// M'Cheyne's calendar cuts inside a chapter, a verse window
/// (`Exodus 11:1-12:21`, `Psalms 119:1-24`).
@immutable
class ReadingSegment {
  final String book; // canonical English name, as in standardBookOrder
  final int from;
  final int to;

  /// First verse of [from]; null = from verse 1.
  final int? fromVerse;

  /// Last verse of [to]; null = to the end of the chapter.
  final int? toVerse;

  const ReadingSegment(this.book, this.from, this.to,
      [this.fromVerse, this.toVerse]);

  bool get wholeChapters => fromVerse == null && toVerse == null;

  @override
  bool operator ==(Object other) =>
      other is ReadingSegment &&
      other.book == book &&
      other.from == from &&
      other.to == to &&
      other.fromVerse == fromVerse &&
      other.toVerse == toVerse;

  @override
  int get hashCode => Object.hash(book, from, to, fromVerse, toVerse);
}

/// One chapter of a [ReadingSession].
@immutable
class ReadingPage {
  final String book; // canonical English name
  final int chapter;
  const ReadingPage(this.book, this.chapter);

  /// Stable text id of the chapter, the unit "read" is recorded in.
  String get key => '$book|$chapter';

  @override
  bool operator ==(Object other) =>
      other is ReadingPage && other.book == book && other.chapter == chapter;

  @override
  int get hashCode => Object.hash(book, chapter);
}

/// What the reader is limited to when it is opened from a reading plan:
/// the chapters of one day, in order, and nothing else. Opening
/// Genesis 1-3 gives a reader of exactly three pages with a progress bar
/// and a back arrow to the plan, not the whole Bible with a Home button.
///
/// A day that has several passages (M'Cheyne has four) is ONE session
/// across all of them, so the bar measures the day, not one passage.
/// A passage that starts or ends inside a chapter still reads as whole
/// chapters here; the reader opens on its first verse.
@immutable
class ReadingSession {
  /// Which of the reader's running plans this day belongs to
  /// ([ReadingPlanProgress.id]); "mark as read" is recorded there.
  final String entryId;
  final int day;
  final List<ReadingPage> pages;
  const ReadingSession(
      {required this.entryId, required this.day, required this.pages});

  factory ReadingSession.forDay(
      String entryId, int day, List<ReadingSegment> segments) {
    final pages = <ReadingPage>[];
    for (final s in segments) {
      for (var c = s.from; c <= s.to; c++) {
        final p = ReadingPage(s.book, c);
        if (!pages.contains(p)) pages.add(p);
      }
    }
    return ReadingSession(entryId: entryId, day: day, pages: pages);
  }

  /// Index of ([englishBook], [chapter]) in [pages], or -1 when the
  /// reader has wandered off the day's chapters (a search result, say).
  int indexOf(String englishBook, int chapter) =>
      pages.indexOf(ReadingPage(englishBook, chapter));
}

/// A reader's own plan: which books, cut into how many days. Stored in
/// the running plan itself, so every device cuts the identical schedule
/// from it ([buildCustomPlan]).
@immutable
class CustomPlanSpec {
  /// Typed by the reader; null/empty = a name made from the books.
  final String? name;

  /// Canonical English names (any order; the plan reads in canon order).
  final List<String> books;

  /// How many reading days the plan is cut into.
  final int days;

  const CustomPlanSpec({this.name, required this.books, required this.days});

  Map<String, Object?> toMap() => {
        if (name != null && name!.trim().isNotEmpty) 'name': name!.trim(),
        'books': books,
        'days': days,
      };

  static CustomPlanSpec? fromMap(Object? m) {
    if (m is! Map) return null;
    final books = m['books'];
    final days = m['days'];
    if (books is! List || days is! num || days < 1) return null;
    final names = [for (final b in books) if (b is String && b.isNotEmpty) b];
    if (names.isEmpty) return null;
    final n = m['name'];
    return CustomPlanSpec(
        name: n is String && n.trim().isNotEmpty ? n.trim() : null,
        books: names,
        days: days.toInt());
  }

  @override
  bool operator ==(Object other) =>
      other is CustomPlanSpec &&
      other.name == name &&
      other.days == days &&
      listEquals(other.books, books);

  @override
  int get hashCode => Object.hash(name, days, Object.hashAll(books));
}

@immutable
class ReadingPlan {
  final String id;
  final int days;

  /// `schedule[d]` is day d+1.
  final List<List<ReadingSegment>> schedule;

  /// Set for a reader's own plan ([id] is `custom`).
  final CustomPlanSpec? spec;
  const ReadingPlan(this.id, this.days, this.schedule, {this.spec});

  List<ReadingSegment> day(int day) =>
      (day < 1 || day > schedule.length) ? const [] : schedule[day - 1];
}

/// Every chapter's verse count, from `assets/chapter_verses.json`
/// (written by tools/build_reading_plans.py from the app's own KJV).
/// What a reader's own plan is balanced on.
class ChapterCatalog {
  /// Canonical order.
  final Map<String, List<int>> verses;
  const ChapterCatalog(this.verses);

  List<String> get books => verses.keys.toList();

  int chapterCount(Iterable<String> books) =>
      books.fold(0, (a, b) => a + (verses[b]?.length ?? 0));

  static ChapterCatalog parse(String raw) {
    final m = jsonDecode(raw) as Map<String, dynamic>;
    return ChapterCatalog({
      for (final e in m.entries)
        e.key: [for (final v in (e.value as List)) (v as num).toInt()],
    });
  }
}

/// Cut [spec]'s books into [CustomPlanSpec.days] runs of whole chapters,
/// balanced by VERSES, in canon order. The same algorithm as
/// tools/build_reading_plans.py's `split`, so a custom plan of the whole
/// Bible in 365 days is exactly the bundled one (a test holds them
/// together). More days than chapters is cut to one chapter a day.
ReadingPlan buildCustomPlan(CustomPlanSpec spec, ChapterCatalog catalog) {
  final wanted = spec.books.toSet();
  final chs = <({String book, int chapter, int verses})>[];
  for (final b in catalog.books) {
    if (!wanted.contains(b)) continue;
    final v = catalog.verses[b]!;
    for (var c = 0; c < v.length; c++) {
      chs.add((book: b, chapter: c + 1, verses: v[c]));
    }
  }
  if (chs.isEmpty) return ReadingPlan('custom', 0, const [], spec: spec);
  final days = spec.days.clamp(1, chs.length);
  final total = chs.fold<int>(0, (a, c) => a + c.verses);
  final schedule = <List<ReadingSegment>>[];
  var i = 0;
  var run = 0;
  for (var k = 1; k <= days; k++) {
    final target = total * k / days;
    final start = i;
    final remaining = days - k;
    while (i < chs.length - remaining) {
      run += chs[i].verses;
      i++;
      if (run >= target) {
        // Step back one chapter when that lands nearer the target (and
        // the day keeps at least one chapter).
        if (i - 1 > start &&
            (run - target) > (target - (run - chs[i - 1].verses))) {
          i--;
          run -= chs[i].verses;
        }
        break;
      }
    }
    if (i == start) {
      run += chs[i].verses;
      i++;
    }
    final segs = <ReadingSegment>[];
    var from = start;
    for (var x = start; x < i; x++) {
      final last = x == i - 1;
      final sameNext = !last &&
          chs[x + 1].book == chs[x].book &&
          chs[x + 1].chapter == chs[x].chapter + 1;
      if (!sameNext) {
        segs.add(ReadingSegment(chs[from].book, chs[from].chapter, chs[x].chapter));
        from = x + 1;
      }
    }
    schedule.add(segs);
  }
  return ReadingPlan('custom', days, schedule, spec: spec);
}

