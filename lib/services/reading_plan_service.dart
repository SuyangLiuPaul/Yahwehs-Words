/// Whole days since 1970-01-01 (UTC) of a calendar date — the compact
/// form a "read on" date is stored in.
int epochDayOf(DateTime d) =>
    DateTime.utc(d.year, d.month, d.day).millisecondsSinceEpoch ~/ 86400000;

DateTime dateOfEpochDay(int e) {
  final u = DateTime.fromMillisecondsSinceEpoch(e * 86400000, isUtc: true);
  return DateTime(u.year, u.month, u.day);
}

/// One plan the reader is running: which plan, from when, what has been
/// read, and how it should remind them. Several can run side by side.
///
/// Stored inside the [ReadingPlansDoc] under [kReadingPlanKey].
///
/// Day numbers in [done] and [skipped] are the PLAN's days (day 12 of
/// the plan), never calendar dates, so moving [start] or pausing never
/// invalidates what has been read.
@immutable
class ReadingPlanProgress {
  /// This running instance. Two copies of the same plan started on
  /// different dates are different instances. Sync merges by it.
  final String id;

  /// Which bundled plan ([ReadingPlan.id]), or `custom`.
  final String planId;

  /// A reader's own plan ([planId] is `custom`): its books and days.
  final CustomPlanSpec? custom;

  /// Local calendar date day 1 falls on (time ignored). The reader can
  /// move it: a plan begun late, or to catch up.
  final DateTime start;

  /// Day numbers (1-based) the reader has marked as read.
  final Set<int> done;

  /// Day numbers the reader chose to leave behind. Not read, but no
  /// longer counted as "behind".
  final Set<int> skipped;

  /// Weekdays (ISO, Mon=1..Sun=7) the plan does not run on. Day 1 is
  /// the first other weekday on or after [start]; a rest day does not
  /// advance the plan and is not reminded.
  final Set<int> restDays;

  /// The date each read day was read ([epochDayOf]); feeds the streak.
  final Map<int, int> doneOn;

  /// Chapters of a day that are already read, while the day is not yet
  /// ([ReadingPage.key]s): a day is read when every chapter in it has
  /// been scrolled to the end.
  final Map<int, Set<String>> readChapters;

  /// While set, the plan's calendar stands still at this date: today
  /// does not advance and no reminder is booked. Resuming moves
  /// [start] on by the days that were paused, so nothing is "missed".
  final DateTime? pausedOn;

  /// Whether this plan reminds the reader. Reminders also need the
  /// notification master switch and the Reading plan category enabled.
  final bool remind;

  /// This plan's own reminder time; null = the Reading plan category's.
  final int? hour;
  final int? minute;

  /// The reader's own words for the reminder's title ("Time to read!").
  /// Null/empty = the plan name and day.
  final String? message;

  /// Epoch ms the plan was started; orders the list.
  final int addedMs;

  /// Epoch ms of the last change; drives cross-device conflict choice.
  final int updatedMs;

  /// Removed. Kept as a tombstone so another device's older copy does
  /// not bring the plan back; dropped after [kReadingPlanTombstoneDays].
  final bool deleted;

  ReadingPlanProgress({
    required this.planId,
    required this.start,
    required this.done,
    required this.updatedMs,
    String? id,
    this.custom,
    this.skipped = const {},
    this.restDays = const {},
    this.doneOn = const {},
    this.readChapters = const {},
    this.pausedOn,
    this.remind = false,
    this.hour,
    this.minute,
    this.message,
    int? addedMs,
    this.deleted = false,
  })  : id = id ?? legacyId(planId, start),
        addedMs = addedMs ?? updatedMs;

  /// The id a pre-1.7.28 single-plan blob gets, derived from what it
  /// holds so two devices that both upgrade it agree on one id.
  static String legacyId(String planId, DateTime start) =>
      'legacy-$planId-${_date(start)}';

  static String _date(DateTime d) =>
      '${d.year.toString().padLeft(4, '0')}-'
      '${d.month.toString().padLeft(2, '0')}-'
      '${d.day.toString().padLeft(2, '0')}';

  static DateTime _dateOnly(DateTime d) => DateTime(d.year, d.month, d.day);

  bool get paused => pausedOn != null;

  /// The rest days in force: all seven would mean never reading, so that
  /// reads as none.
  Set<int> get effectiveRestDays => restDays.length >= 7 ? const {} : restDays;

  Map<String, Object?> toMap() => {
        'id': id,
        'planId': planId,
        if (custom != null) 'custom': custom!.toMap(),
        'start': _date(start),
        'done': (done.toList()..sort()),
        if (skipped.isNotEmpty) 'skipped': (skipped.toList()..sort()),
        if (restDays.isNotEmpty) 'rest': (restDays.toList()..sort()),
        if (doneOn.isNotEmpty)
          'doneOn': {
            for (final k in (doneOn.keys.toList()..sort())) '$k': doneOn[k],
          },
        if (readChapters.isNotEmpty)
          'chapters': {
            for (final k in (readChapters.keys.toList()..sort()))
              '$k': (readChapters[k]!.toList()..sort()),
          },
        if (pausedOn != null) 'pausedOn': _date(pausedOn!),
        'remind': remind,
        if (hour != null && minute != null) 'hour': hour,
        if (hour != null && minute != null) 'minute': minute,
        if (message != null && message!.isNotEmpty) 'message': message,
        'addedMs': addedMs,
        'updatedMs': updatedMs,
        if (deleted) 'deleted': true,
      };

  String toJson() => jsonEncode(toMap());

  static Set<int> _days(Object? v) => {
        for (final d in (v is List ? v : const []))
          if (d is num && d >= 1) d.toInt(),
      };

  /// Null for anything that is not a well-formed entry. [legacy]: the
  /// 1.7.26/27 single-plan blob, which had no `remind` and reminded
  /// whenever the category was on.
  static ReadingPlanProgress? fromMap(Object? m, {bool legacy = false}) {
    if (m is! Map) return null;
    final planId = m['planId'];
    final start = DateTime.tryParse('${m['start']}');
    if (planId is! String || planId.isEmpty || start == null) return null;
    final custom = CustomPlanSpec.fromMap(m['custom']);
    if (planId == 'custom' && custom == null) return null;
    final ts = m['updatedMs'];
    final updated = ts is num ? ts.toInt() : 0;
    final paused = m['pausedOn'] == null
        ? null
        : DateTime.tryParse('${m['pausedOn']}');
    final h = m['hour'];
    final mi = m['minute'];
    final hasTime = h is num && mi is num;
    final msg = m['message'];
    final added = m['addedMs'];
    final id = m['id'];
    final doneOn = <int, int>{};
    final rawOn = m['doneOn'];
    if (rawOn is Map) {
      for (final e in rawOn.entries) {
        final k = int.tryParse('${e.key}');
        final v = e.value;
        if (k != null && k >= 1 && v is num) doneOn[k] = v.toInt();
      }
    }
    final chapters = <int, Set<String>>{};
    final rawCh = m['chapters'];
    if (rawCh is Map) {
      for (final e in rawCh.entries) {
        final k = int.tryParse('${e.key}');
        final v = e.value;
        if (k != null && k >= 1 && v is List) {
          chapters[k] = {for (final c in v) if (c is String) c};
        }
      }
    }
    return ReadingPlanProgress(
      id: id is String && id.isNotEmpty ? id : null,
      planId: planId,
      custom: custom,
      start: _dateOnly(start),
      done: _days(m['done']),
      skipped: _days(m['skipped']),
      restDays: {
        for (final d in (m['rest'] is List ? m['rest'] as List : const []))
          if (d is num && d >= 1 && d <= 7) d.toInt(),
      },
      doneOn: doneOn,
      readChapters: chapters,
      pausedOn: paused == null ? null : _dateOnly(paused),
      remind: m['remind'] is bool ? m['remind'] as bool : legacy,
      hour: hasTime ? h.toInt().clamp(0, 23) : null,
      minute: hasTime ? mi.toInt().clamp(0, 59) : null,
      message: msg is String && msg.trim().isNotEmpty ? msg.trim() : null,
      addedMs: added is num ? added.toInt() : null,
      updatedMs: updated,
      deleted: m['deleted'] == true,
    );
  }

  /// One entry from its JSON text (the 1.7.26/27 blob, or [toJson]).
  static ReadingPlanProgress? tryParse(Object? raw) {
    if (raw is! String || raw.isEmpty) return null;
    try {
      final m = jsonDecode(raw);
      return fromMap(m, legacy: m is Map && m['remind'] == null);
    } catch (_) {
      return null;
    }
  }

  ReadingPlanProgress copyWith({
    Set<int>? done,
    Set<int>? skipped,
    Set<int>? restDays,
    Map<int, int>? doneOn,
    Map<int, Set<String>>? readChapters,
    DateTime? start,
    DateTime? pausedOn,
    bool clearPausedOn = false,
    bool? remind,
    int? hour,
    int? minute,
    bool clearTime = false,
    String? message,
    bool clearMessage = false,
    int? updatedMs,
    bool? deleted,
  }) =>
      ReadingPlanProgress(
        id: id,
        planId: planId,
        custom: custom,
        start: start == null ? this.start : _dateOnly(start),
        done: done ?? this.done,
        skipped: skipped ?? this.skipped,
        restDays: restDays ?? this.restDays,
        doneOn: doneOn ?? this.doneOn,
        readChapters: readChapters ?? this.readChapters,
        pausedOn: clearPausedOn
            ? null
            : (pausedOn == null ? this.pausedOn : _dateOnly(pausedOn)),
        remind: remind ?? this.remind,
        hour: clearTime ? null : (hour ?? this.hour),
        minute: clearTime ? null : (minute ?? this.minute),
        message: clearMessage ? null : (message ?? this.message),
        addedMs: addedMs,
        updatedMs: updatedMs ?? this.updatedMs,
        deleted: deleted ?? this.deleted,
      );

  /// Which plan day [today] is, counted from [start] (day 1 = the first
  /// non-rest day on or after it). Can be < 1 (start in the future) or >
  /// the plan length (finished on the calendar). Uses UTC dates so a
  /// daylight-saving change can never make a 23- or 25-hour "day" round
  /// to the wrong number — the bug `day_of_year` had (2026-09-08). A
  /// paused plan counts as if today were the day it was paused. On a
  /// rest day it is still yesterday's day: nothing new falls due.
  int calendarDay(DateTime today) {
    var t = _dateOnly(today);
    final p = pausedOn;
    if (p != null && p.isBefore(t)) t = p;
    final diff = DateTime.utc(t.year, t.month, t.day)
        .difference(DateTime.utc(start.year, start.month, start.day))
        .inDays;
    final rest = effectiveRestDays;
    if (diff < 0 || rest.isEmpty) return diff + 1;
    final n = diff + 1;
    var count = (n ~/ 7) * (7 - rest.length);
    var wd = start.weekday;
    for (var i = 0; i < n % 7; i++) {
      if (!rest.contains(wd)) count++;
      wd = wd % 7 + 1;
    }
    return count;
  }

  /// The date plan day [day] falls on.
  DateTime dateOfDay(int day) {
    final rest = effectiveRestDays;
    if (day < 1 || rest.isEmpty) {
      return DateTime(start.year, start.month, start.day + (day < 1 ? 0 : day - 1));
    }
    var d = start;
    var c = 0;
    while (true) {
      if (!rest.contains(d.weekday)) {
        c++;
        if (c == day) return d;
      }
      d = DateTime(d.year, d.month, d.day + 1);
    }
  }

  /// The start date that makes [day] fall on [on] (or, if [on] is a rest
  /// day, on the last day before it that is not).
  DateTime startForDayOn(DateTime on, int day) {
    final rest = effectiveRestDays;
    var cur = _dateOnly(on);
    if (rest.isEmpty) return DateTime(cur.year, cur.month, cur.day - (day - 1));
    while (rest.contains(cur.weekday)) {
      cur = DateTime(cur.year, cur.month, cur.day - 1);
    }
    var c = 1;
    while (c < day) {
      cur = DateTime(cur.year, cur.month, cur.day - 1);
      if (!rest.contains(cur.weekday)) c++;
    }
    return cur;
  }

  /// [date] is one of the plan's rest days.
  bool isRestDate(DateTime date) =>
      effectiveRestDays.contains(_dateOnly(date).weekday);

  /// First day neither read nor skipped, or null when every day is.
  int? firstUnread(int days) {
    for (var d = 1; d <= days; d++) {
      if (!done.contains(d) && !skipped.contains(d)) return d;
    }
    return null;
  }
}

/// `uiStrings[key]` in [locale], English if missing, with `{name}`
/// placeholders replaced.
String rpText(String key, String locale, [Map<String, Object> params = const {}]) {
  var t = uiStrings[key]?[locale] ?? uiStrings[key]?['en'] ?? key;
  params.forEach((k, v) => t = t.replaceAll('{$k}', '$v'));
  return t;
}

/// "Genesis 1-3" / "创世记 1-3" / "Exodus 11:1-12:21", in the reader's language.
String readingSegmentLabel(ReadingSegment s, String locale) {
  final book = localeAwareBookName(s.book, locale);
  final range = s.wholeChapters
      ? (s.from == s.to ? '${s.from}' : '${s.from}-${s.to}')
      : _windowLabel(s);
  return '$book $range';
}

String _windowLabel(ReadingSegment s) {
  final a = s.fromVerse;
  final b = s.toVerse;
  if (s.from == s.to) {
    if (a != null && b != null) return '${s.from}:$a-$b';
    if (a != null) return '${s.from}:$a-';
    return '${s.from}:1-$b';
  }
  return '${s.from}${a != null ? ':$a' : ''}-${s.to}${b != null ? ':$b' : ''}';
}

/// Where a reader stands, worked out from progress and the calendar.
/// Pure, so the rules (including every edge) are tested without a UI.
@immutable
class ReadingPlanStatus {
  /// The plan's start date is still in the future.
  final bool notStarted;

  /// Every day is read or skipped.
  final bool finished;

  /// The calendar ran past the last day but days remain unread.
  final bool calendarEnded;

  /// The reader paused this plan.
  final bool paused;

  /// Today is one of the plan's rest days: nothing new falls due.
  final bool restDay;

  /// Day to show as "today": calendar day clamped to 1..days.
  final int today;

  /// Days before [today] that are neither read nor skipped.
  final int unreadBefore;

  /// First day not yet read or skipped (null when finished).
  final int? resumeDay;

  final int doneCount;
  final int skippedCount;
  final int days;

  const ReadingPlanStatus({
    required this.notStarted,
    required this.finished,
    required this.calendarEnded,
    required this.paused,
    required this.restDay,
    required this.today,
    required this.unreadBefore,
    required this.resumeDay,
    required this.doneCount,
    required this.skippedCount,
    required this.days,
  });

  /// True when [today] is the day to read and it is not yet ticked.
  bool todayPending(Set<int> done) => !finished && !done.contains(today);
}

ReadingPlanStatus readingPlanStatus(
    ReadingPlanProgress p, int days, DateTime now) {
  final done = p.done.where((d) => d >= 1 && d <= days).toSet();
  final skipped =
      p.skipped.where((d) => d >= 1 && d <= days && !done.contains(d)).toSet();
  final cal = p.calendarDay(now);
  final today = cal < 1 ? 1 : (cal > days ? days : cal);
  var unreadBefore = 0;
  for (var d = 1; d < today; d++) {
    if (!done.contains(d) && !skipped.contains(d)) unreadBefore++;
  }
  final finished = done.length + skipped.length >= days;
  return ReadingPlanStatus(
    notStarted: cal < 1,
    finished: finished,
    calendarEnded: !finished && cal > days,
    paused: p.paused,
    restDay: !finished && !p.paused && p.isRestDate(now),
    today: today,
    unreadBefore: unreadBefore,
    resumeDay:
        finished ? null : p.copyWith(done: done, skipped: skipped).firstUnread(days),
    doneCount: done.length,
    skippedCount: skipped.length,
    days: days,
  );
}

/// A plan's name for the reader: the bundled plan's, or the reader's own
/// words, or one made from the books of their own plan.
String readingPlanName(ReadingPlan plan, String locale) {
  final spec = plan.spec;
  if (spec == null) return rpText('readingPlan_${plan.id}_name', locale);
  final typed = spec.name;
  if (typed != null && typed.trim().isNotEmpty) return typed.trim();
  final order = [...spec.books];
  String b(String x) => localeAwareBookName(x, locale);
  final String label;
  if (order.length <= 2) {
    label = order.map(b).join(', ');
  } else {
    label = '${b(order.first)}–${b(order.last)}';
  }
  return rpText('readingPlan_customAuto', locale,
      {'books': label, 'days': plan.days});
}

/// The reminder for one running plan on the day of [fire], or null when
/// there is nothing worth saying (no plan, plan finished or paused, the
/// day not started yet, or that day already ticked). Pure.
///
/// [fire] is the day the notification is for, which is not always today:
/// the native scheduler books the next two weeks, each with ITS day's
/// passages, because a repeating notification would repeat day 1's
/// chapters for ever.
///
/// Day for a given date: the calendar day from the start date; once the
/// calendar has run past the end, the first day still unread. A day that
/// is already ticked is skipped — nobody needs a nudge to read what they
/// have read — but only the days they have actually ticked can be known,
/// so a future day's reminder is still booked and the next app open
/// re-books without it.
///
/// The title is the reader's own [ReadingPlanProgress.message] when they
/// wrote one, else the plan's name and day. Several plans run at once,
/// so the name is always needed to tell two reminders apart.
({String title, String body})? readingPlanReminder({
  required ReadingPlanProgress? progress,
  required ReadingPlan? plan,
  required DateTime fire,
  required String locale,
}) {
  if (progress == null || plan == null || progress.paused) return null;
  if (progress.isRestDate(fire)) return null; // a rest day: nothing to nudge
  final st = readingPlanStatus(progress, plan.days, fire);
  if (st.finished || st.notStarted) return null;
  final day = st.calendarEnded ? st.resumeDay : st.today;
  if (day == null || progress.done.contains(day) || progress.skipped.contains(day)) {
    return null;
  }
  final segs = plan.day(day);
  if (segs.isEmpty) return null;
  final msg = progress.message;
  return (
    title: (msg != null && msg.trim().isNotEmpty)
        ? msg.trim()
        : rpText('readingPlan_notifTitle', locale, {
            'name': readingPlanName(plan, locale),
            'day': day,
            'days': plan.days,
          }),
    body: segs.map((x) => readingSegmentLabel(x, locale)).join(' · '),
  );
}

/// How long a removed plan is remembered so another device's older copy
/// cannot bring it back.
const int kReadingPlanTombstoneDays = 90;

/// Everything stored under [kReadingPlanKey]: the reader's running plans.
///
/// Format v2 (1.7.28):
/// `{"v":2,"updatedMs":…,"clearedMs":…,"plans":[{entry}…]}`.
/// Parses the two older shapes as well — the 1.7.26/27 single-plan blob
/// (`{"planId","start","done","updatedMs"}`) becomes one entry and its
/// "stopped" form (`{"planId":"","updatedMs"}`) becomes an empty list
/// that remembers when it was stopped ([clearedMs]) so a stale plan on
/// another device cannot undo the stop.
@immutable
class ReadingPlansDoc {
  /// Every entry, including tombstones ([ReadingPlanProgress.deleted]).
  final List<ReadingPlanProgress> entries;

  /// Entries last changed at or before this are dropped.
  final int clearedMs;
  final int updatedMs;

  const ReadingPlansDoc(
      {required this.entries, this.clearedMs = 0, this.updatedMs = 0});

  /// What the reader sees: not removed, not older than a stop.
  List<ReadingPlanProgress> get active => [
        for (final e in entries)
          if (!e.deleted && e.updatedMs > clearedMs) e,
      ]..sort(_byAdded);

  static int _byAdded(ReadingPlanProgress a, ReadingPlanProgress b) {
    final c = a.addedMs.compareTo(b.addedMs);
    return c != 0 ? c : a.id.compareTo(b.id);
  }

  String toJson() {
    final all = [...entries]..sort(_byAdded);
    return jsonEncode({
      'v': 2,
      'updatedMs': updatedMs,
      if (clearedMs > 0) 'clearedMs': clearedMs,
      'plans': [for (final e in all) e.toMap()],
    });
  }

  /// Null for anything that is not a reading-plan blob.
  static ReadingPlansDoc? parse(Object? raw) {
    if (raw is! String || raw.isEmpty) return null;
    try {
      final m = jsonDecode(raw);
      if (m is! Map) return null;
      final ts = m['updatedMs'];
      final stamp = ts is num ? ts.toInt() : 0;
      if (m['plans'] is List) {
        final cl = m['clearedMs'];
        final entries = <ReadingPlanProgress>[
          for (final e in (m['plans'] as List))
            if (ReadingPlanProgress.fromMap(e) case final p?) p,
        ];
        return ReadingPlansDoc(
          entries: entries,
          clearedMs: cl is num ? cl.toInt() : 0,
          updatedMs: stamp,
        );
      }
      if (m['planId'] is String) {
        if ((m['planId'] as String).isEmpty) {
          return ReadingPlansDoc(entries: const [], clearedMs: stamp, updatedMs: stamp);
        }
        final e = ReadingPlanProgress.fromMap(m, legacy: true);
        if (e == null) return null;
        return ReadingPlansDoc(entries: [e], updatedMs: e.updatedMs);
      }
      return null;
    } catch (_) {
      return null;
    }
  }
}

/// Merge two copies of one running plan (same [ReadingPlanProgress.id]).
/// What was read or skipped on either device stays read or skipped; every
/// other field comes from the more recently changed copy (ties broken by
/// the text of the entry, so both devices pick the same one).
ReadingPlanProgress _mergeEntry(ReadingPlanProgress a, ReadingPlanProgress b) {
  final aNewer = a.updatedMs != b.updatedMs
      ? a.updatedMs > b.updatedMs
      : a.toJson().compareTo(b.toJson()) >= 0;
  final newer = aNewer ? a : b;
  // Read-on dates: the earliest wins, so a streak never shortens.
  final doneOn = {...a.doneOn};
  b.doneOn.forEach((k, v) {
    final have = doneOn[k];
    doneOn[k] = have == null || v < have ? v : have;
  });
  final chapters = <int, Set<String>>{};
  for (final m in [a.readChapters, b.readChapters]) {
    m.forEach((k, v) => chapters[k] = {...?chapters[k], ...v});
  }
  final done = {...a.done, ...b.done};
  chapters.removeWhere((k, _) => done.contains(k));
  return newer.copyWith(
    done: done,
    doneOn: doneOn,
    readChapters: chapters,
    skipped: {...a.skipped, ...b.skipped},
    updatedMs: a.updatedMs > b.updatedMs ? a.updatedMs : b.updatedMs,
  );
}

/// Merge rule for cross-device sync (used by RealtimeDbSyncService).
///
/// Plans are matched by their instance id: the days read on either
/// device are kept (a chapter read on the phone is read on the laptop);
/// everything else (start date, reminder, paused, removed) follows the
/// newer change. A plan one device does not have is added, unless the
/// other device removed or stopped it more recently.
String? mergeReadingPlanBlobs(Object? local, Object? remote) {
  final l = ReadingPlansDoc.parse(local);
  final r = ReadingPlansDoc.parse(remote);
  final lStr = local is String && local.isNotEmpty ? local : null;
  final rStr = remote is String && remote.isNotEmpty ? remote : null;
  if (l == null || r == null) {
    if (l == null && r == null) {
      if (lStr == null) return rStr;
      if (rStr == null) return lStr;
      return readingPlanBlobStamp(rStr) > readingPlanBlobStamp(lStr) ? rStr : lStr;
    }
    return l == null ? rStr : lStr;
  }
  final byId = <String, ReadingPlanProgress>{};
  for (final e in [...l.entries, ...r.entries]) {
    final have = byId[e.id];
    byId[e.id] = have == null ? e : _mergeEntry(have, e);
  }
  final cleared = l.clearedMs > r.clearedMs ? l.clearedMs : r.clearedMs;
  final kept = [
    for (final e in byId.values)
      if (e.updatedMs > cleared) e,
  ];
  var stamp = l.updatedMs > r.updatedMs ? l.updatedMs : r.updatedMs;
  for (final e in kept) {
    if (e.updatedMs > stamp) stamp = e.updatedMs;
  }
  if (cleared > stamp) stamp = cleared;
  return ReadingPlansDoc(entries: kept, clearedMs: cleared, updatedMs: stamp)
      .toJson();
}

/// `updatedMs` of any reading-plan blob, active or stopped; 0 if none.
int readingPlanBlobStamp(String raw) {
  try {
    final m = jsonDecode(raw);
    final ts = m is Map ? m['updatedMs'] : null;
    return ts is num ? ts.toInt() : 0;
  } catch (_) {
    return 0;
  }
}

/// How many days in a row the reader has read, across every plan.
@immutable
class ReadingStreak {
  /// Consecutive days up to today (or up to yesterday: a streak is not
  /// broken until a whole day has passed without reading).
  final int current;
  final int longest;

  /// Distinct days with any reading.
  final int totalDays;
  const ReadingStreak(this.current, this.longest, this.totalDays);
}

ReadingStreak readingStreak(Iterable<ReadingPlanProgress> entries, DateTime now) {
  final days = <int>{
    for (final e in entries)
      if (!e.deleted) ...e.doneOn.values,
  };
  if (days.isEmpty) return const ReadingStreak(0, 0, 0);
  final sorted = days.toList()..sort();
  var longest = 1;
  var run = 1;
  for (var i = 1; i < sorted.length; i++) {
    run = sorted[i] == sorted[i - 1] + 1 ? run + 1 : 1;
    if (run > longest) longest = run;
  }
  final today = epochDayOf(now);
  var cursor = days.contains(today) ? today : today - 1;
  var current = 0;
  while (days.contains(cursor)) {
    current++;
    cursor--;
  }
  return ReadingStreak(current, longest, days.length);
}

/// A plan the scheduler should book reminders for, with its own time
/// when it has one.
@immutable
class ReadingReminderSlot {
  final ReadingPlanProgress entry;
  final int? hour;
  final int? minute;
  const ReadingReminderSlot(this.entry, this.hour, this.minute);
}

/// What recording a chapter as read did.
enum ChapterReadResult { notTracked, already, partial, dayDone }

/// Bundled plans + the active profile's running plans.
class ReadingPlanService extends ChangeNotifier {
  ReadingPlanService._() {
    // A profile switch and a sync download both end in
    // ProfileService.notifyListeners (realtime_db_sync_service.dart
    // _applyRemoteSuppressed); either can change what is stored.
    ProfileService.instance.addListener(_onProfileChanged);
  }
  static final ReadingPlanService instance = ReadingPlanService._();

  void _onProfileChanged() {
    if (_progressLoaded) reload();
  }

  /// Test hook: replace how the asset is read.
  @visibleForTesting
  Future<String> Function(String path)? loader;

  /// Test hook: a fixed "now".
  @visibleForTesting
  DateTime Function()? clock;

  /// Called (about a second after the last change) when stored plans
  /// changed, so notifications can be re-booked. main.dart wires it.
  VoidCallback? onPersisted;
  Timer? _persistedTimer;

  DateTime get now => (clock ?? DateTime.now)();

  List<ReadingPlan>? _plans;
  ChapterCatalog? _catalog;
  Future<List<ReadingPlan>>? _loading;
  final Map<String, ReadingPlan> _customCache = {};
  List<ReadingPlanProgress> _all = const [];
  int _clearedMs = 0;
  bool _progressLoaded = false;

  /// The reader's running plans, oldest first.
  List<ReadingPlanProgress> get entries =>
      ReadingPlansDoc(entries: _all, clearedMs: _clearedMs).active;

  ReadingPlanProgress? entry(String? id) {
    for (final e in entries) {
      if (e.id == id) return e;
    }
    return null;
  }

  bool get progressLoaded => _progressLoaded;

  ChapterCatalog? get catalog => _catalog;

  /// Parse the asset. Pure, so tests can feed it a string.
  static List<ReadingPlan> parse(String raw) {
    final m = jsonDecode(raw) as Map<String, dynamic>;
    return [
      for (final p in (m['plans'] as List).cast<Map<String, dynamic>>())
        ReadingPlan(
          p['id'] as String,
          p['days'] as int,
          [
            for (final day in (p['schedule'] as List))
              [
                for (final s in (day as List).cast<List>())
                  ReadingSegment(
                    s[0] as String,
                    s[1] as int,
                    s[2] as int,
                    s.length > 3 ? s[3] as int? : null,
                    s.length > 4 ? s[4] as int? : null,
                  ),
              ],
          ],
        ),
    ];
  }

  /// The bundled plans (and, with them, the chapter table a reader's own
  /// plan is cut from).
  Future<List<ReadingPlan>> plans() {
    if (_plans != null) return Future.value(_plans);
    return _loading ??= () async {
      final read = loader ?? rootBundle.loadString;
      final raw = await read('assets/reading_plans.json');
      _catalog = ChapterCatalog.parse(await read('assets/chapter_verses.json'));
      return _plans = parse(raw);
    }();
  }

  /// A bundled plan by id.
  Future<ReadingPlan?> plan(String? id) async {
    if (id == null) return null;
    for (final p in await plans()) {
      if (p.id == id) return p;
    }
    return null;
  }

  /// The plan a running entry follows — bundled, or built from its own
  /// books. Null until [plans] has loaded, or if the plan is gone.
  ReadingPlan? planFor(ReadingPlanProgress e) {
    final spec = e.custom;
    if (spec != null) {
      final cat = _catalog;
      if (cat == null) return null;
      return _customCache.putIfAbsent(
          '${e.id}|${spec.hashCode}', () => buildCustomPlan(spec, cat));
    }
    for (final p in _plans ?? const <ReadingPlan>[]) {
      if (p.id == e.planId) return p;
    }
    return null;
  }

  Future<ReadingPlan?> planForAsync(ReadingPlanProgress e) async {
    await plans();
    return planFor(e);
  }

  String get _key => ProfileService.instance.scopedKey(kReadingPlanKey);

  /// (Re)read the plans for the active profile. Call after a profile
  /// switch or a sync download.
  Future<void> reload() async {
    final prefs = await SharedPreferences.getInstance();
    final doc = ReadingPlansDoc.parse(prefs.getString(_key));
    _all = doc?.entries ?? const [];
    _clearedMs = doc?.clearedMs ?? 0;
    _progressLoaded = true;
    notifyListeners();
  }

  Future<void> _save() async {
    final ms = now.millisecondsSinceEpoch;
    final cutoff = ms - kReadingPlanTombstoneDays * 86400000;
    _all = [
      for (final e in _all)
        if (!(e.deleted && e.updatedMs < cutoff)) e,
    ];
    var stamp = _clearedMs;
    for (final e in _all) {
      if (e.updatedMs > stamp) stamp = e.updatedMs;
    }
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(
        _key,
        ReadingPlansDoc(entries: _all, clearedMs: _clearedMs, updatedMs: stamp)
            .toJson());
    _progressLoaded = true;
    notifyListeners();
    try {
      RealtimeDbSyncService.instance.requestUpload();
    } catch (_) {
      // Sync is best-effort (signed out, China build, tests).
    }
    _persistedSoon();
  }

  void _persistedSoon() {
    if (onPersisted == null) return;
    _persistedTimer?.cancel();
    _persistedTimer =
        Timer(const Duration(seconds: 1), () => onPersisted?.call());
  }

  Future<void> _update(
      String id, ReadingPlanProgress Function(ReadingPlanProgress e) change) async {
    final i = _all.indexWhere((e) => e.id == id && !e.deleted);
    if (i < 0) return;
    final next = [..._all];
    next[i] = change(_all[i]).copyWith(updatedMs: _stamp(_all[i]));
    _all = next;
    await _save();
  }

  /// A change time that is always newer than the entry's last one, even
  /// when two changes land in the same millisecond or the clock stepped
  /// back, so the merge never prefers the older of two edits.
  int _stamp(ReadingPlanProgress e) {
    final t = now.millisecondsSinceEpoch;
    return t > e.updatedMs ? t : e.updatedMs + 1;
  }

  DateTime get _today {
    final n = now;
    return DateTime(n.year, n.month, n.day);
  }

  static int _seq = 0;

  /// Start [planId] (or the reader's own [custom] plan) on [startDate]
  /// (default today) alongside any plans already running. Null when
  /// [kMaxReadingPlans] are already kept.
  Future<ReadingPlanProgress?> start(
    String planId, {
    CustomPlanSpec? custom,
    DateTime? startDate,
    Set<int> restDays = const {},
    bool remind = false,
    int? hour,
    int? minute,
    String? message,
  }) async {
    if (entries.length >= kMaxReadingPlans) return null;
    final d = startDate ?? now;
    final day = DateTime(d.year, d.month, d.day);
    var ms = now.millisecondsSinceEpoch;
    // Creation order is the list order, so never tie with a plan already
    // there (two starts inside one millisecond, or a clock stepped back).
    for (final x in _all) {
      if (x.addedMs >= ms) ms = x.addedMs + 1;
    }
    final e = ReadingPlanProgress(
      id: '$planId-${ReadingPlanProgress._date(day)}-${ms.toRadixString(36)}'
          '-${(_seq++).toRadixString(36)}',
      planId: custom == null ? planId : 'custom',
      custom: custom,
      start: day,
      done: const {},
      restDays: restDays.length >= 7 ? const {} : restDays,
      remind: remind,
      hour: hour,
      minute: hour == null ? null : minute,
      message: (message ?? '').trim().isEmpty ? null : message!.trim(),
      addedMs: ms,
      updatedMs: ms,
    );
    _all = [..._all, e];
    await _save();
    return e;
  }

  /// Run the same plan again from today, with the same reminder.
  Future<ReadingPlanProgress?> restart(String id) async {
    final e = entry(id);
    if (e == null) return null;
    return start(e.planId,
        custom: e.custom,
        restDays: e.restDays,
        remind: e.remind,
        hour: e.hour,
        minute: e.minute,
        message: e.message);
  }

  /// Remove a plan (and what was read in it).
  Future<void> remove(String id) =>
      _update(id, (e) => e.copyWith(deleted: true));

  /// Mark a whole day read (or not) by hand. Reading it in the app does
  /// the same through [markChapterRead].
  Future<void> setDone(String id, int day, bool done) => _update(id, (e) {
        final next = {...e.done};
        final on = {...e.doneOn};
        final chapters = {...e.readChapters};
        if (done) {
          next.add(day);
          on.putIfAbsent(day, () => epochDayOf(now));
          chapters.remove(day);
        } else {
          next.remove(day);
          on.remove(day);
          chapters.remove(day);
        }
        // Read beats skipped: a day cannot be both.
        return e.copyWith(
            done: next,
            doneOn: on,
            readChapters: chapters,
            skipped: {...e.skipped}..remove(day));
      });

  /// Record that the reader scrolled to the end of [chapterKey]
  /// ([ReadingPage.key]) while reading [day] of plan [id]. When every
  /// chapter of the day has been, the day is read.
  Future<ChapterReadResult> markChapterRead(
      String id, int day, String chapterKey) async {
    final e = entry(id);
    if (e == null) return ChapterReadResult.notTracked;
    final plan = await planForAsync(e);
    if (plan == null) return ChapterReadResult.notTracked;
    final wanted = ReadingSession.forDay(id, day, plan.day(day))
        .pages
        .map((p) => p.key)
        .toSet();
    if (!wanted.contains(chapterKey)) return ChapterReadResult.notTracked;
    if (e.done.contains(day)) return ChapterReadResult.already;
    final have = {...?e.readChapters[day]};
    if (have.contains(chapterKey)) return ChapterReadResult.already;
    have.add(chapterKey);
    final complete = have.containsAll(wanted);
    await _update(id, (x) {
      if (!complete) {
        return x.copyWith(readChapters: {...x.readChapters, day: have});
      }
      return x.copyWith(
        done: {...x.done, day},
        doneOn: {...x.doneOn}..putIfAbsent(day, () => epochDayOf(now)),
        readChapters: {...x.readChapters}..remove(day),
        skipped: {...x.skipped}..remove(day),
      );
    });
    return complete ? ChapterReadResult.dayDone : ChapterReadResult.partial;
  }

  /// Chapters of [day] already read (while the day is not yet done).
  Set<String> chaptersRead(String id, int day) =>
      entry(id)?.readChapters[day] ?? const {};

  /// Move day 1 to [date]. What has been read stays read.
  Future<void> setStart(String id, DateTime date) =>
      _update(id, (e) => e.copyWith(start: date));

  /// Choose the weekdays the plan does not run on (ISO, Mon=1..Sun=7).
  /// Today stays the same plan day where it can: the start date is moved
  /// so the reader does not suddenly find themselves days ahead or behind.
  Future<void> setRestDays(String id, Set<int> rest) async {
    final e = entry(id);
    if (e == null) return;
    final plan = planFor(e);
    final clean = rest.length >= 7 ? <int>{} : rest;
    await _update(id, (x) {
      final before = x.calendarDay(_today);
      final changed = x.copyWith(restDays: clean);
      if (plan == null || before < 1 || before > plan.days) return changed;
      return changed.copyWith(start: changed.startForDayOn(_today, before));
    });
  }

  /// Freeze the plan's calendar today; no reminders until [resume].
  Future<void> pause(String id) => _update(id, (e) {
        if (e.paused) return e;
        return e.copyWith(pausedOn: _today);
      });

  /// Carry on: today becomes the plan day it was when paused, so the
  /// plan picks up exactly where it stopped, with nothing behind.
  Future<void> resume(String id) => _update(id, (e) {
        final p = e.pausedOn;
        if (p == null) return e;
        final today = _today;
        final dayAtPause = e.calendarDay(today); // clamped to the pause date
        if (dayAtPause >= 1) {
          return e.copyWith(
              start: e.startForDayOn(today, dayAtPause), clearPausedOn: true);
        }
        final gap = DateTime.utc(today.year, today.month, today.day)
            .difference(DateTime.utc(p.year, p.month, p.day))
            .inDays;
        final s = e.start;
        return e.copyWith(
          start: DateTime(s.year, s.month, s.day + (gap > 0 ? gap : 0)),
          clearPausedOn: true,
        );
      });

  /// "Pick up where I left off": slide the schedule so the first unread
  /// day is today. Nothing is lost and nothing is marked read.
  Future<void> catchUp(String id) async {
    final e = entry(id);
    final plan = e == null ? null : await planForAsync(e);
    if (e == null || plan == null) return;
    final first = e.firstUnread(plan.days);
    if (first == null) return;
    await setStart(id, e.startForDayOn(_today, first));
  }

  /// "Leave the missed days behind": every unread day before today is
  /// skipped, so it stops counting as behind. Today stays to be read.
  Future<void> skipMissed(String id) async {
    final e = entry(id);
    final plan = e == null ? null : await planForAsync(e);
    if (e == null || plan == null) return;
    final st = readingPlanStatus(e, plan.days, now);
    final add = <int>{
      for (var d = 1; d < st.today; d++)
        if (!e.done.contains(d)) d,
    };
    if (add.isEmpty) return;
    await _update(id, (x) => x.copyWith(skipped: {...x.skipped, ...add}));
  }

  /// "I already read these": every unread day before today is marked
  /// read (for a reader who followed the plan on paper, or elsewhere).
  Future<void> markMissedRead(String id) async {
    final e = entry(id);
    final plan = e == null ? null : await planForAsync(e);
    if (e == null || plan == null) return;
    final st = readingPlanStatus(e, plan.days, now);
    final add = <int>{
      for (var d = 1; d < st.today; d++)
        if (!e.done.contains(d)) d,
    };
    if (add.isEmpty) return;
    await _update(id, (x) {
      final on = {...x.doneOn};
      for (final d in add) {
        // The day it fell on, not today, so a streak is not invented.
        on.putIfAbsent(d, () => epochDayOf(x.dateOfDay(d)));
      }
      final chapters = {...x.readChapters}..removeWhere((k, _) => add.contains(k));
      return x.copyWith(
        done: {...x.done, ...add},
        doneOn: on,
        readChapters: chapters,
        skipped: {...x.skipped}..removeAll(add),
      );
    });
  }

  /// Set the plan's reminder. [hour]/[minute] null with [clearTime]
  /// returns it to the Reading plan category's time.
  Future<void> setReminder(
    String id, {
    bool? remind,
    int? hour,
    int? minute,
    bool clearTime = false,
    String? message,
    bool clearMessage = false,
  }) =>
      _update(
          id,
          (e) => e.copyWith(
                remind: remind,
                hour: hour,
                minute: minute,
                clearTime: clearTime,
                message: message,
                clearMessage: clearMessage,
              ));

  /// The plans the scheduler should book reminders for: reminding, not
  /// paused, not finished.
  Future<List<ReadingReminderSlot>> reminderSlots() async {
    if (!_progressLoaded) await reload();
    final out = <ReadingReminderSlot>[];
    for (final e in entries) {
      if (!e.remind || e.paused) continue;
      final plan = await planForAsync(e);
      if (plan == null) continue;
      if (readingPlanStatus(e, plan.days, now).finished) continue;
      out.add(ReadingReminderSlot(e, e.hour, e.minute));
      if (out.length >= kMaxReadingPlans) break;
    }
    return out;
  }

  /// One running plan's reminder for [fire] (see [readingPlanReminder]).
  Future<({String title, String body})?> reminderForEntry(
      ReadingPlanProgress e, DateTime fire, String locale) async {
    return readingPlanReminder(
      progress: e,
      plan: await planForAsync(e),
      fire: fire,
      locale: locale,
    );
  }

  /// Everything due on [fire] as ONE notification, for the web, which
  /// has a single time per category: the plan's own reminder when one is
  /// due, or a short list when several are.
  Future<({String title, String body})?> reminderFor(
      DateTime fire, String locale) async {
    final lines = <({String title, String body})>[];
    for (final slot in await reminderSlots()) {
      final r = await reminderForEntry(slot.entry, fire, locale);
      if (r != null) lines.add(r);
    }
    if (lines.isEmpty) return null;
    if (lines.length == 1) return lines.first;
    return (
      title: rpText('readingPlan_notifMany', locale, {'n': lines.length}),
      body: lines.map((l) => '${l.title}: ${l.body}').join('\n'),
    );
  }

  // ── The calendar moves while the app is open ──────────────────────

  _DayWatch? _watch;

  /// Keep "today" honest while the app stays open: at midnight, and when
  /// the app returns to the foreground after one (a phone left on a desk
  /// overnight, a tab left open), re-read the day and re-book reminders.
  /// Called once from main.dart; tests leave it off so no timer is pending.
  void startDayWatch() {
    _watch ??= _DayWatch(this)..start();
  }

  @visibleForTesting
  void dayChangedForTest() => _dayChanged();

  DateTime? _lastDay;

  void _dayChanged() {
    final t = _today;
    if (_lastDay != null && _lastDay == t) return;
    _lastDay = t;
    notifyListeners();
    _persistedSoon();
  }
}

class _DayWatch with WidgetsBindingObserver {
  final ReadingPlanService svc;
  Timer? _timer;
  _DayWatch(this.svc);

  void start() {
    svc._lastDay = svc._today;
    WidgetsBinding.instance.addObserver(this);
    _arm();
  }

  void _arm() {
    _timer?.cancel();
    final n = svc.now;
    final next = DateTime(n.year, n.month, n.day + 1, 0, 0, 2);
    _timer = Timer(next.difference(n), () {
      svc._dayChanged();
      _arm();
    });
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) {
      svc._dayChanged();
      _arm();
    }
  }
}
