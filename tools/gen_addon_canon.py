#!/usr/bin/env python3
"""Generate lib/utils/addons/addon_canon.dart.

The add-on importer needs the canon in a form that does not depend on the
rest of the app: 66 books in order, how many verses each chapter has (the
KJV versification theWord's text modules are laid out in), and each book's
name in the three scripts the reader can show. It is GENERATED from
`assets/chapter_verses.json` and `lib/constants/book_name_mapping.dart`
so it cannot be typed wrong, and `test/addons/addon_canon_test.dart`
re-derives it and fails if either source moves.

    python3 tools/gen_addon_canon.py            # write
    python3 tools/gen_addon_canon.py --check    # fail on drift

Run it in whichever repo you changed; the output is identical in both apps
except for nothing — the file has no package imports at all.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "utils", "addons", "addon_canon.dart")


def grab(src, name):
    m = re.search(r"const " + name + r" = \{(.*?)\n\};", src, re.S)
    return dict(re.findall(r"""["']([^"']+)["']\s*:\s*["']([^"']+)["']""", m.group(1)))


def verse_counts():
    """Verses per chapter per book. Words ships assets/chapter_verses.json;
    Sword derives the same table from its bundled KJV (the two agree — the
    canon test in each repo proves it)."""
    path = os.path.join(ROOT, "assets", "chapter_verses.json")
    if os.path.exists(path):
        return json.load(open(path))
    seen = {}
    for r in json.load(open(os.path.join(ROOT, "assets", "kjv.json"))):
        ch = seen.setdefault(r["book"], {})
        c, v = int(r["chapter"]), int(r["verse"])
        ch[c] = max(ch.get(c, 0), v)
    return {b: [ch[c] for c in range(1, max(ch) + 1)] for b, ch in seen.items()}


def build():
    counts = verse_counts()
    src = open(os.path.join(ROOT, "lib", "constants", "book_name_mapping.dart")).read()
    hans = grab(src, "englishToChinese")
    hant = grab(src, "englishToChineseTraditional")
    books = list(counts.keys())
    assert len(books) == 66, len(books)
    missing = [b for b in books if b not in hans or b not in hant]
    assert not missing, missing
    out = []
    out.append("// GENERATED by tools/gen_addon_canon.py — do not edit by hand.\n"
               "// Sources: assets/chapter_verses.json (or kjv.json), lib/constants/book_name_mapping.dart.\n"
               "// `test/addons/addon_canon_test.dart` fails when either moves.\n"
               "//\n"
               "// No imports on purpose: the importer's pure-Dart half must run on the\n"
               "// plain VM and be identical in Words and Sword.\n"
               "library;\n")
    out.append("/// The 66 canonical books, in canon order, by the English name every\n"
               "/// edition's `Verse.id` resolves to.\n"
               "const List<String> kCanonBooks = [")
    for b in books:
        out.append(f"  {json.dumps(b)},")
    out.append("];\n")
    out.append("/// Verses in each chapter of each book (KJV versification), by canon\n"
               "/// index. 31,102 in all — the line count of a theWord `.ont`.\n"
               "const List<List<int>> kCanonVerseCounts = [")
    for b in books:
        out.append("  [" + ", ".join(str(n) for n in counts[b]) + "],")
    out.append("];\n")
    for var, doc, names in (
        ("kCanonBooksHans", "Simplified Chinese names, canon order.", hans),
        ("kCanonBooksHant", "Traditional Chinese names, canon order.", hant),
    ):
        out.append(f"/// {doc}\nconst List<String> {var} = [")
        for b in books:
            out.append(f"  {json.dumps(names[b], ensure_ascii=False)},")
        out.append("];\n")
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            print("addon_canon.dart is out of date; run tools/gen_addon_canon.py")
            sys.exit(1)
        print("addon_canon.dart is current")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
